async function seedMarketplaceCatalog(pool) {
  if (!DEFAULT_CATALOG.length) return;

  const placeholders = DEFAULT_CATALOG.map(() => '(?, ?, ?, ?, ?, ?, ?)').join(', ');
  const values = DEFAULT_CATALOG.flatMap((item) => [
    item.slug,
    item.name,
    item.item_type,
    item.asset_json,
    item.price_coins,
    item.is_tradable !== undefined ? item.is_tradable : 1,
    item.sort_order,
  ]);

  await pool.query(
    `INSERT INTO marketplace_items (slug, name, item_type, asset_json, price_coins, is_tradable, sort_order)
     VALUES ${placeholders}
     ON DUPLICATE KEY UPDATE
       name = VALUES(name),
       item_type = VALUES(item_type),
       asset_json = VALUES(asset_json),
       price_coins = VALUES(price_coins),
       is_tradable = VALUES(is_tradable),
       sort_order = VALUES(sort_order)`,
    values
  );
}

module.exports = { DEFAULT_CATALOG, seedMarketplaceCatalog };
